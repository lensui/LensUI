const GRID_LABELS_BY_LOCALE: Record<TableLocaleCode, TableLabels> = {
  'zh-CN': ZH_CN_GRID_LABELS,
  'en-US': EN_US_GRID_LABELS,
};

export function resolveGridLocale(config: TableLocaleConfig | undefined): { language: TableLocaleCode; labels: TableLabels } {
  if (!config || typeof config === 'string') {
    const language = config ?? 'zh-CN';
    return { language, labels: GRID_LABELS_BY_LOCALE[language] };
  }

  const { language = 'zh-CN', labels } = config;
  return { language, labels: { ...GRID_LABELS_BY_LOCALE[language], ...labels } };
}
